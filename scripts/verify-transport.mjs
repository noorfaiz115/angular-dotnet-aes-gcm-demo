import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from '../src/client/node_modules/typescript/lib/typescript.js';
const code = ts.transpileModule(fs.readFileSync(new URL('../src/client/src/app/encrypted-transport.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { EncryptedTransport } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const base = process.env.DEMO_URL ?? 'http://localhost:5100';
const path = '/api/secure/echo';
const transport = new EncryptedTransport(base);
const send = envelope => fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(envelope) });
const roundTrip = await transport.post(path, { message: 'नमस्ते 🔐', nested: { count: 42 } });
assert.deepEqual(roundTrip.plaintext.received, { message: 'नमस्ते 🔐', nested: { count: 42 } });
assert.equal((await send(roundTrip.request)).status, 409, 'replay rejected');
const fresh = await transport.encrypt(path, { message: 'tamper test' });
const damaged = structuredClone(fresh);
const tag = Buffer.from(damaged.tag, 'base64'); tag[0] ^= 1; damaged.tag = tag.toString('base64');
assert.equal((await send(damaged)).status, 400, 'bad tag rejected');
const validResponse = await send(fresh);
assert.equal(validResponse.status, 200, 'invalid tag must not consume request ID');
const reply = await validResponse.json();
assert.equal((await transport.decrypt(path, fresh, reply)).received.message, 'tamper test');
await assert.rejects(() => transport.decrypt(path, fresh, { ...reply, requestId: crypto.randomUUID() }));
const responseTag = Buffer.from(reply.tag, 'base64'); responseTag[0] ^= 1;
await assert.rejects(() => transport.decrypt(path, fresh, { ...reply, tag: responseTag.toString('base64') }));
const wrongPath = await transport.encrypt('/api/secure/other', { message: 'bound to path' });
assert.equal((await send(wrongPath)).status, 400);
const badNonce = await transport.encrypt(path, {});
assert.equal((await send({ ...badNonce, nonce: 'AA==' })).status, 400);
assert.equal((await send({ ...badNonce, sessionId: 'unknown' })).status, 409);
const parallel = await Promise.all(Array.from({ length: 5 }, (_, index) => transport.post(path, { index })));
assert.deepEqual(parallel.map(x => x.plaintext.received.index), [0, 1, 2, 3, 4]);
console.log('PASS: Web Crypto/.NET Unicode round trip, replay, request/response tampering, request binding, path binding, nonce validation, unknown session, concurrent requests.');
const duplicate = await transport.encrypt(path, { message: 'concurrent duplicate' });
const duplicateStatuses = (await Promise.all([send(duplicate), send(duplicate)])).map(x => x.status).sort();
assert.deepEqual(duplicateStatuses, [200, 409], 'atomic replay rejection');
const bootstrap = await fetch(base + '/api/crypto/session', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ publicKey: 'invalid' }) });
assert.equal(bootstrap.status, 400, 'malformed public key rejected');
